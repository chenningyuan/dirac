def read_hdf5(file_name):
    """
    Open hdf5-type file and return dictionary of its contents
    """
    import h5py
    data_dict = {}
    with h5py.File(file_name, 'r') as h5file:
        recursively_load_dict_contents_from_group(h5file, data_dict,'/')
    return data_dict

def recursively_load_dict_contents_from_group(h5file, data_dict, path):
    """
    Modified from code found at Stack Exchange to get flat dictionary
    """
    import h5py
    for key, item in h5file[path].items():
        if isinstance(item, h5py._hl.dataset.Dataset):
            data_dict[path+key] = {}
            data_dict[path+key]['value'] = item[()]
        elif isinstance(item, h5py._hl.group.Group):
           recursively_load_dict_contents_from_group(h5file, data_dict, path + key + '/')


def get_grid_from_data(data):
    labels=['coor_'+str(ind) for ind in range(4)]
    if '/result/grid/points/weights' in data.keys():
        labels.append('weights')
    grid_xyz={}
    for k in labels:
        for x in data.keys():
            if k in x:
                grid_xyz[k] = data[x]["value"]
    return grid_xyz

def get_from_hdf5(s,data):
    labels=[s+'_dim_'+str(ind) for ind in range(4)]
    data_values={}
    for k in labels:
        for x in data.keys():
            if k in x:
                data_values[k] = data[x]["value"]
    return data_values
 
 
def data_to_cube(df, gf, cube_file,origin=(0.0, 0.0, 0.0),spacing=(1.0, 1.0, 1.0),atom_info=None):

    df = df.sort_values(by=["coor_3", "coor_2", "coor_1"])
    x_vals = np.sort(df["coor_1"].unique())
    y_vals = np.sort(df["coor_2"].unique())
    z_vals = np.sort(df["coor_3"].unique())
    nx, ny, nz = len(x_vals), len(y_vals), len(z_vals)
    dx, dy, dz = spacing
    values = df[gf].values.reshape((nz, ny, nx))
    with open(cube_file, 'w') as f:
        # Header
        f.write("Generated by CSV to Cube Converter\n")
        f.write("OUTER LOOP: X, MIDDLE LOOP: Y, INNER LOOP: Z\n")

        # Origin and grid size
        natoms = len(atom_info) if atom_info else 0
        f.write(f"{natoms:5d}{origin[0]:12.6f}{origin[1]:12.6f}{origin[2]:12.6f}\n")
        f.write(f"{nx:5d}{dx:12.6f}{0.0:12.6f}{0.0:12.6f}\n")
        f.write(f"{ny:5d}{0.0:12.6f}{dy:12.6f}{0.0:12.6f}\n")
        f.write(f"{nz:5d}{0.0:12.6f}{0.0:12.6f}{dz:12.6f}\n")

        # Atom info (fake hydrogen atoms if none provided)
        if atom_info:
            for atom in atom_info:
                atomic_num, charge, x, y, z = atom
                f.write(f"{atomic_num:5d}{charge:12.6f}{x:12.6f}{y:12.6f}{z:12.6f}\n")
        else:
            pass  # Empty atom list

        # Data block: Write values in z-fastest order
        count = 0
        for ix in range(nx):
            for iy in range(ny):
                for iz in range(nz):
                    f.write(f"{values[iz, iy, ix]:13.5e}")
                    count += 1
                    if count % 6 == 0:
                        f.write("\n")
        if count % 6 != 0:
            f.write("\n")

    print(f"Cube file written to {cube_file}")


def mol_from_xyz(fmol):
    periodic_table = Chem.GetPeriodicTable()
    atom_info=[]
    charge=0.0  # fixme; assumed charge
    with open(fmol) as f:
        lines=f.readlines()
        for line in lines[2:]:
            atom_symbol,x,y,z=line.strip().split()
            atom_info.append([periodic_table.GetAtomicNumber(atom_symbol),charge,float(x),float(y),float(z)])
    return atom_info

def get_tuple(s):
    splitted=s.strip('(').strip(')').split()
    return tuple(float(x.strip(',')) for x in splitted)

data=read_hdf5(args.fh5)

if args.data == 'grid':
    grid_xyz=get_grid_from_data(data)
    
    df=pd.DataFrame.from_dict(grid_xyz)
    if args.fcsv is not None:
        df.to_csv(args.fcsv,index=False,float_format="%.8e")
        print(f"CSV file written to {args.fcsv}")
    if args.ftxt is not None:
        df.to_csv(args.ftxt,index=False,sep=' ',float_format="%.8e")
        print(f"TXT file written to {args.ftxt}")
    else:
        print('grid can only be converted to CSV/TXT file')

elif args.data == 'grid_function':
    grid_xyz=get_grid_from_data(data)
    
    if args.data_labels is not None:
        data_values={}
        for k in args.data_labels:
            for x in data.keys():
                if k in x:
                    data_values[k] = data[x]["value"]
    else:
        print('specify grid function labels')
        sys.exit()

    prep=grid_xyz | data_values
    df=pd.DataFrame.from_dict(prep)
    if args.fcsv is not None:
        df.to_csv(args.fcsv,index=False,float_format="%.8e")
        print(f"CSV file written to {args.fcsv}")
    if args.ftxt is not None:
        df.to_csv(args.ftxt,index=False,sep=' ',header=False,float_format="%.8e")
        print(f"TXT file written to {args.ftxt}")
    if args.fcube is not None:
        for k in data_values.keys():
            fcube=args.fcube.replace('.cube','.'+k.replace('/','_')+'.cube')
            if args.mol:
                atom_info=mol_from_xyz(args.mol)
            else:
                atom_info=None
            if args.spacing:
                spacing=get_tuple(args.spacing)
            else:
                tmp=get_from_hdf5('spacing',data)
                order=['spacing_dim_1', 'spacing_dim_2', 'spacing_dim_3']
                spacing=tuple([tmp[x][0] for x in order])
            if args.origin:
                origin=get_tuple(args.origin)
            else:
                tmp=get_from_hdf5('origin',data)
                order=['origin_dim_1', 'origin_dim_2', 'origin_dim_3']
                origin=tuple([tmp[x][0] for x in order])
            data_to_cube(df,k,fcube,origin=origin,spacing=spacing,atom_info=atom_info)
    else:
        print('Unknown key.Stop')


else:
    print('unknown argument to "-data"')
    sys.exit()




