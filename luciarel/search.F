C****** NAME SEARCH
      SUBROUTINE SEARCH(IUNIT,A)
      IMPLICIT CHARACTER*8 (A-H,O-Z)
      DIMENSION B(4)
      DATA A1/'********'/
CICI1     READ (IUNIT,END=3) B
1     READ (IUNIT,END=3) B(1)
CLGM      IF(EOF(IUNIT).NE.0) GO TO 3
CICI2     IF(B(1).NE.A1.OR.B(4).NE.A) GO TO 1
2     IF(B(1).NE.A1) GO TO 1
      BACKSPACE IUNIT
      READ(IUNIT) B
      IF(B(4).NE.A) GO TO 1
      RETURN
3     WRITE (6,4) A,IUNIT
CLGM      ENDFILE 6
4     FORMAT(5X,A8,'NOT FOUND ON UNIT',I3)
      Call Abend()
      END
