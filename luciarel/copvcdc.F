      SUBROUTINE COPVCDC(LUIN,LUOUT,VEC1,IREW,LBLK)
*
* Copy complex vector from LUIN to LUOUT
*
      IMPLICIT REAL*8(A-H,O-Z)
      DIMENSION VEC1(*)
*
      IF(IREW.NE.0) THEN
        CALL REWINE(LUIN,LBLK)
        CALL REWINE(LUOUT,LBLK)
      END IF
*
*. Real part
      CALL COPVCD(LUIN,LUOUT,VEC1,0,LBLK)
*. Imaginary part
      CALL COPVCD(LUIN,LUOUT,VEC1,0,LBLK)
*
      RETURN
      END
