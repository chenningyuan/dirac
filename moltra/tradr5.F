C&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&
C/* Deck trdr5t */
      SUBROUTINE TRDR5T(WORK,KFREE,LFREE,IPRINT,INTFLG,
     &                  NSTR,ANTIS,LMP2,KINDX,KQ,KE,KIBE,DINTSKP)
C***********************************************************************
C
C     Driver for scheme 5: Based on scheme 4
C     1)  Loop over distributions (pq|**), transform 2 indices
C        (pq|**) --> (ij|pq)
C     2)  transform 3rd index (ij|**) --> (ij|k*)
C     3)  contract 3/4 transformed integrals with T matrix to form
C         one index transformed Lagrangian
C         L_(*n)=(ij|k*)*T_(ijkn)
C     4)  transform 2nd Lagrangian index
C         L_(*n) --> L_(mn)
C
C     Parallel scheme.
C
C     * VECTORS:
C       Qi             - coefficients for index i
C       NSTR(ifrp,0,i) - total number of orbitals for index i
C       NSTR(ifrp,1,i) - number of electronic orbitals for index i
C       NSTR(ifrp,2,i) - number of positronic orbitals for index i
C     * AO-INTEGRALS:
C     Distributions (pq|**) are fetched by CALDIS and are packed on
C     boson irreps. The information necessary for symmetry packing
C     is provided by the integer array INDX (generated by NINSH):
C       INDX(1,INDA)   - Position of function in block 
C       INDX(2,INDA)   - Irreducible representation of function
C       INDX(3,INDA)   - Position of function within this particular irrep
C                        and block
C                        (INDA refers to index of SO-orbital)
C     * CONTROL INFORMATION:
C       MSOUT = .TRUE. - write transformed integrals to file
C       EIGN           - eigenvalues (for  MP2 calculation)
C       INTFLG - flag of what integral types to transform
C
C     
C     Written by Joost van Stralen - march 2003
C
C***********************************************************************
#include "implicit.h"
#include "priunit.h"
      PARAMETER(D0=0.0D0)
#include "mxorb.h"
#include "aovec.h"
#if defined (VAR_MPI)
      INCLUDE 'mpif.h'
      DIMENSION ISTAT(MPI_STATUS_SIZE)
#endif
#include "infpar.h"
#include "dcbgen.h"
#include "dcborb.h"
#include "dcbtra.h"
#include "dcbtr3.h"
#include "dcbbas.h"
#include "dgroup.h"

#include "blocks.h"
      LOGICAL ANTIS,LMP2,TRIAN(2)
      DIMENSION NSTR(2,0:2,4),
     &          KQ(2,4),KE(2,4),KIBE(2,4),WORK(*),DINTSKP(*)
      DIMENSION IPTQLAG(0:7,0:7,2)
C     
      CALL QENTER('TRDR5T')
      KFRSAV = KFREE
C     
C     Define the packing of the 4-index transformed integrals
C
      TRIAN(1) = ISAME(1).EQ.ISAME(2)
      TRIAN(2) = .FALSE.
      CALL PCK2IN(NSTR,TRIAN,IPRINT)
C
C     Prepare for screening
C
      IF(SCRTRA.GT.D0) THEN
        CALL PR4SCR(KGAB,KDRIJ,WORK,KFREE,LFREE,DINTSKP,
     &              WORK(KQ(1,1)),WORK(KQ(1,2)),
     &              WORK(KQ(1,3)),WORK(KQ(1,4)),
     &              NDMOQR,ICMOQR,NSTR,ISAME,IPRINT)
      ELSE
        KDRIJ = KFREE
        KGAB  = KFREE
      ENDIF
C
C     *****************************************
C     ****** P A R A L L E L    C O D E  ******
C     *****************************************
C
#if defined (VAR_MPI)
      IF (PARCAL) THEN
C
C       Get hold of the slaves
C       ( ITASK = 2 for parallel integral transformation )
C
        CALL DIRAC_PARCTL( 2 )
C
C       Initialize
C
        CALL TRAPARI(WORK,KFREE,LFREE,KQ,KE,KIBE,
     &               KINDX,KGAB,KDRIJ,INTFLG,NSTR,ANTIS,LMP2)
C
C
C     We send out all the tasks (shell pairs in this case) to the slaves
C     - reverse order of IC and ISHLA to get better load balancing
C       - S blocks are generally bigger than L blocks
C       - if IBSTEP is big the load is generally larger for bigger ISHLA
C         because ISHLB loop in TRDRV4 must end at ISHLA
C
C       FIXME: calculate IBSTEP dynamically based on number of nodes
C       and size of shells.
C       (currently, it is just an input parameter for the wizards)
        MXIBSTEP = IPAR4BS
        IF (MXIBSTEP .LE. 0) THEN
C           ... determine MXIBSTEP based on number of nodes and
C               number of shell pairs to give optimal load balancing
C               (minimize N**5*nbstep in second half transformation
C                while having work for all nodes) /LV+HJAaJ Aug 2001
C     
           MXIBSTEP = NTR4BSTEP(INTFLG,I2TYP,NODES)
           WRITE(LUPRI,'(/A,I4)')
     &     ' * Max no. of B shells in a task determined to be',
     &     MXIBSTEP 
        END IF      
C    
        CALL GETTIM(CPUBEF,WALLBEF)
        DO IC = 2, 1, -1
           WRITE(LUPRI,'(1X,A,I1)') '- Integral class ',IC
           CALL SHRNGE (IC,INTFLG,I2TYP,IASTRT,IBSTRT,IASMAX,IBSMAX)
           DO ISHLA = IASMAX, IASTRT, -1
              CALL GETTIM(CPUST,WALLST)
              WRITE(LUPRI,'(3X,A,I4,A,F14.2,A)')
     &           '- Starting shell A no. ',ISHLA,' after ',
     &           WALLST - WALLBEF,' seconds.'
              CALL FLSHFO(LUPRI)
C             Distribute number of B's evenly
              NBSTEP = (ISHLA-IBSTRT)/MXIBSTEP + 1
              IBSTEP = -(ISHLA-IBSTRT)/NBSTEP - 1
           DO IBEND = ISHLA, IBSTRT, IBSTEP
C
              ISHLB = MAX(IBEND+IBSTEP+1,IBSTRT)
C
              CALL MPI_RECV(ITEST,1,MPI_INTEGER,MPI_ANY_SOURCE,20,
     &                      MPI_COMM_WORLD,ISTAT,IERR)
              NWHO = ISTAT(MPI_SOURCE)
              IF (ITEST .EQ. 0) THEN
C             ... slave wants new set of A,B shells
              CALL GETTIM(CPUST,WALLST)
              IF (IPRINT .GE. 3) THEN
                 WRITE(LUPRI,'(3X,4(A,I4),A,F10.2,A)')
     &              '- Sending shells (',ISHLA,',',ISHLB,
     &              '-',IBEND,') to node',NWHO,
     &              ' after',WALLST-WALLBEF,' seconds'
                 CALL FLSHFO(LUPRI)
              END IF
              CALL MPI_SEND(ISHLA,1,MPI_INTEGER,NWHO,30,
     &                      MPI_COMM_WORLD,IERR)
              CALL MPI_SEND(ISHLB,1,MPI_INTEGER,NWHO,30,
     &                      MPI_COMM_WORLD,IERR)
              CALL MPI_SEND(IBEND,1,MPI_INTEGER,NWHO,30,
     &                      MPI_COMM_WORLD,IERR)
              CALL MPI_SEND(IC,1,MPI_INTEGER,NWHO,30,
     &                      MPI_COMM_WORLD,IERR)
              CALL MPI_SEND(I2TYP,1,MPI_INTEGER,NWHO,30,
     &                      MPI_COMM_WORLD,IERR)
              ELSE IF (ABS(ITEST) .LE. 2) THEN
C             ... slave wants to lock or free file
                 CALL QUIT('lock/free file not implemented yet')
              ELSE
                 CALL QUIT('Illegal ITEST')
              END IF
           ENDDO
           ENDDO
        ENDDO
C
C       Get the slaves out of the transformation loop
C       and receive final results
C
        CALL TRARES(WORK,KFREE,LFREE,DINTSKP,LMP2,DUM,DUM)
      ELSE
#endif
C
C     *************************************
C     ****** S E R I A L    C O D E  ******
C     *************************************
C
C
        CALL GETTIM(CPUBEF,WALLBEF)
        DO IC = 1, 2
           WRITE(LUPRI,'(1X,A,I1)') '- Integral class ',IC
           CALL SHRNGE (IC,INTFLG,I2TYP,IASTRT,IBSTRT,IASMAX,IBSMAX)
           CALL MEMGET('REAL',KTQMAT,NPTQLAG,WORK,KFREE,LFREE)
           CALL DZERO(WORK(KTQMAT),NPTQLAG)
           DO ISHLA = IASTRT, IASMAX
              CALL GETTIM(CPUST,WALLST)
              WRITE(LUPRI,'(3X,2(A,I4),A,F10.2,A/32X,A,F10.2,A)')
     &           '- Beginning with task',ISHLA,' of',IASMAX,
     &           ' after',WALLST-WALLBEF,' seconds',
     &        'and after',CPUST-CPUBEF,' CPU-seconds'
              CALL FLSHFO(LUPRI)
              CALL TRDRV5(WORK,KFREE,LFREE,IPRINT,INTFLG,
     &                   NSTR,IPTQLAG,NPTQLAG,WORK(KINDX),TRIAN,
     &                   KQ,KE,KIBE,IC,I2TYP,IBSTRT,ISHLA,
     &                   WORK(KDRIJ),WORK(KGAB),WORK(KTQMAT),DINTSKP)
           ENDDO            
           CALL MEMREL('TRDR5T1',WORK,1,KTQMAT,KFREE,LFREE)
        ENDDO               
#if defined (VAR_MPI)
      ENDIF                 
#endif        
C             
C      +-------------------------------------------------+ 
C      |                                                 |
C      |   Transform the AO index of the Lagrangian      |
C      |                                                 |
C      +-------------------------------------------------+
C          
C      ...
C
C             
C     Screening statistics
C
      IF(SCRTRA.GT.D0) THEN
        CALL ST4SCR(DINTSKP)
      ENDIF
C
C     Release the slaves if we run in parallel.
C        ( ITASK = -1 )
C     
      IF (PARCAL) CALL DIRAC_PARCTL( -1 )
C
      CALL MEMREL('TRDR5T2',WORK,KFRSAV,KFRSAV,KFREE,LFREE)
      CALL QEXIT('TRDR5T')
C          
      RETURN
C          
      END  
C&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&
C/* Deck TRDRV5 */
      SUBROUTINE TRDRV5(WORK,KFREE,LFREE,IPRINT,INTFLG,
     &                  NSTR,IPTQLAG,NPTQLAG,INDX,TRIAN,KQ,KE,KIBE,
     &                  IC,I2TYP,IBSTRT,IBEND,DRIJ,GABRAO,TQMAT,
     &                  DINTSKP)
C
C     This is a modified version of TRDRV4 that makes the
C     Lagrangian in a mixed AO,MO form.
C
C     Formulas :
C
C     xxxx
C
C     Written by Joost van Stralen & Luuk Visscher, march 2003
C
C&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&
#include "implicit.h"
#include "maxaqn.h"
#include "priunit.h"
#include "iratdef.h"
#include "mxorb.h"
#include "dcbgen.h"
#include "dcbtra.h"
#include "dcbtr3.h"
#include "dcbbas.h"
#include "dcborb.h"
#include "dgroup.h"
#include "twosta.h"
      LOGICAL NOPV, NODV, TRIAN(2)
      DIMENSION NSTR(2,0:2,4),INDX(3,*)
      DIMENSION KQ(2,4),KE(2,4),KIBE(2,4)
      DIMENSION IJP12(0:7)
      DIMENSION IHTM(0:7),MHTM(2),NHTM(2), IOFFB(0:7)
      DIMENSION IRECC(2),NBFSZ(2),NBUF(2),NIJBUF(2),NHTIM(2),IBOFF(2)
      DIMENSION WORK(*),GABRAO(*),DRIJ(*),DINTSKP(*)
C
      CALL QENTER('TRDRV5')
      KFRSAV = KFREE
C
C     We transform all shells in the first halftransformation
C
      CALL ICOPY ( 32,NSPCK,1,NSPCK12,1)
      CALL ICOPY (196,ISPCK,1,ISPCK12,1)
      CALL ICOPY ( 24,NBBAS,1,NBBAS1, 1)
      CALL ICOPY ( 24,NBBAS,1,NBBAS2, 1)
      CALL ICOPY ( 24,IBBAS,1,IBBAS1, 1)
      CALL ICOPY ( 24,IBBAS,1,IBBAS2, 1)
      CALL ICOPY (  2,IBAS, 1,IBAS1,  1)
      CALL ICOPY (  2,IBAS, 1,IBAS2,  1)
C
C     Copy the first half of the NDMOQ and ICMOQ arrays
C
      CALL ICOPY (8,NDMOQR,1,NDMOQS,1)
      CALL ICOPY (8,NDMOQR,1,NDMOQT,1)
      CALL ICOPY (4,ICMOQR,1,ICMOQS,1)
      CALL ICOPY (4,ICMOQR,1,ICMOQT,1)
C
C     Set up symmetry packing for reduced shell space in the second
C     half transformation. We have one index that has a range of 
C     active shells and one index that should belong to a particular
C     shell (ISHLA).
C
      CALL GISPCK(NSPCK34,ISPCK34,ISHLA,IBSTRT,IBEND,
     &     NBBAS3,NBBAS4,IBBAS3,IBBAS4,IBAS3,IBAS4)
C
C     Generate pointers for the reduced coefficient matrices
C     As we leave the last index untransformed we need only
C     one coefficient matrix and not two as in TRDRV4.
C     Also we need only the square form as a quater transformation
C     cannot be done on triangular arrays.
C
      NQ4S = 0
      DO IFSYM = 1, NFSYM
         NROW4 = 0
         DO IREPR = 0, NBSYM-1 
            IF (IFSYM.EQ.JBTOF(IREPR,IC)) THEN
               NROW4 = NROW4 + NBBAS4(IREPR,IC)
            ENDIF
         ENDDO
C
         NDMOQS(1,IFSYM,4) = NROW4
         NDMOQS(2,IFSYM,4) = NDMOQR(2,IFSYM,4)
C
         ICMOQS(IFSYM,4) = NQ4S + 1
         NQ4S = NQ4S + NROW4 * NDMOQR(2,IFSYM,4) * NZ
      ENDDO
C
C     Get the reduced coefficient matrices (only active shells)
C
      CALL MEMGET('REAL',KQ4S,NQ4S,WORK,KFREE,LFREE)
      DO IFSYM = 1, NFSYM
        IF(NDMOQR(2,IFSYM,4)*NDMOQS(2,IFSYM,4).NE.0) THEN
          CALL QREDUC (IBSTRT,IBEND,IFSYM,WORK(KQ(IFSYM,4)),
     &                NDMOQR(1,IFSYM,4),NDMOQR(2,IFSYM,4),
     &                WORK(KQ4S+ICMOQS(IFSYM,4)-1),
     &                NDMOQS(1,IFSYM,4),NDMOQS(2,IFSYM,4))
        ENDIF
      ENDDO
C
C     Make index array for half-transformed integrals
C
      NHTMT = 0
      DO IREPIJ = 1, NFSYM
         MHTM(IREPIJ) = 0
         NHTM(IREPIJ) = 0
         DO IREPAB = 0, NBSYM-1
            IF (IREPIJ.EQ.JBTOF(IREPAB,1)) THEN
               IHTM(IREPAB) = MHTM(IREPIJ) + NHTMT
               MHTM(IREPIJ) = MHTM(IREPIJ) + NSPCK34(IREPAB,0)*NZ
            ENDIF
            NHTM(IREPIJ) = MHTM(IREPIJ)*NFPCK12(IREPIJ)
         ENDDO
         NHTMT = NHTMT + NHTM(IREPIJ)
      ENDDO
C
      IF (I2TYP.LT.0) THEN
         GOTO 999
      ELSEIF (I2TYP.EQ.1) THEN
         ICS12 = 1
         ICF12 = 1
      ELSEIF (I2TYP.EQ.2) THEN
         ICS12 = 2
         ICF12 = 2
      ELSE
         ICS12 = 1
         ICF12 = 2
      ENDIF
C
C     Memory requirements for HERMIT:
C
      MWHER = MXMEMHER(IC,I2TYP)
C
C     Loop over the shells
C
      CALL IZERO(IOFFB,8)
      DO ISHLB = IBSTRT, IBEND
C
         KFRSAV3 = KFREE
         NINSHA  = NINSH(ISHLA,-1,INDX,IPRINT)
         NINSHB  = NINSH(ISHLB,-1,INDX,IPRINT)
         IF (IPRINT .GE. 3) WRITE(LUPRI,'(/A,2I3)')
     &      '    ---> TRDRV5 : integrals for shell A/B',ISHLA,ISHLB
C
         LDXAB = 5*NINSHA*NINSHB
         CALL MEMGET('INTE',KDXAB  ,LDXAB  ,WORK,KFREE,LFREE)
C
C           Set up gather array for distributions, 
C           calculate memory requirements for this batch.
C
C           NOTE : The actual dimension of INDXAB is kept in the
C           common block dcbtra.h. When we want to parallelize it may
C           be better to allocate it always as MXINSH*MXINSH*4,
C           or (even better) to send it also down to HERMIT.
C           Luuk. TODO
C
C           First a dummy run to calculate the memory requirements
C           for GMAT. We assume that HMAT is not more than twice GMAT,
C           and reserve the same memory also for use in HERMIT.
C
C        The size of HMAT is approximately: 
C           NUMDIS * NFPCK12(IREPIJ) * NZ / NPASS
C
C        (1) overhead: Subtract 10% or 1MW from available memory 
C
         MFREE = LFREE - MIN(LFREE/10, 1 000 000)
C
C        (2) We must be able to hold
C            (a) GMAT + HERMIT
C            (b) GMAT + HMAT
C            simultaneously in memory.
C 
C
         IF (MWHER .GT. MFREE) CALL QUIT('Not enough memory for HERMIT')
C            
         MWHMAT = 0
         IT = 0
 2000    CONTINUE
            IT = IT + 1
            NSIZG = MFREE - MAX(MWHMAT,MWHER)
C
C           Calculate NUMDIS and NSIZG
C           --------------------------
C
            NUMDIS = NDISTRN(I2TYP,IPRINT,.FALSE.,.FALSE.,
     &                       .FALSE.,INDX,WORK(KFREE),IJP12,NSIZG,IDUM)
C
C           Setup INDXAB & IJPASS
C           ---------------------
C
            CALL MEMGET('INTE',KIJPASS,8*NPASS,WORK,KFREE,LFREE)
C
            NUMDIS = NDISTRN(I2TYP,IPRINT,.TRUE.,.TRUE.,.FALSE.,
     &                       INDX,WORK(KDXAB),IJP12,NSIZG,WORK(KIJPASS))
C
C           Calculate MWHMAT:
C           -----------------
C
            MWHMAT = MWHMATCALC(WORK(KIJPASS),NPASS,NFPCK12)
C
            CALL MEMREL('TRDRV5.mwhmat calc',WORK,1,KIJPASS,KFREE,LFREE)
C
C           Check that we fit in memory
C           ---------------------------
C
            IF (IPRINT .GE. 3) THEN
               WRITE(LUPRI,'(A,I3,A/4(A,I9))')
     &         '       - TRDRV5 memory estimate iteration no. ',IT,' :',
     &         '         Free: ',MFREE,', Hermit: ',MWHER,
     &         ', HMAT ',MWHMAT,', GMAT ',NSIZG
            END IF
            CALL FLSHFO(LUPRI)
            IF ( (NSIZG + MAX(MWHMAT,MWHER) ) .GT. MFREE ) THEN
               IF ( MWHMAT .GT. MFREE) THEN
                  MWHMAT = MFREE * 9 / 10
               END IF
               GOTO 2000
            END IF
C
C        Final calculation of INDXAB & IJPASS
C
         CALL MEMGET('INTE',KIJPASS,8*NPASS,WORK,KFREE,LFREE)
C
         NUMDIS = NDISTRN(I2TYP,IPRINT,.TRUE.,.TRUE.,.FALSE.,
     &                    INDX,WORK(KDXAB),IJP12,NSIZG,WORK(KIJPASS))
C
         IF (IPRINT .GE. 3) THEN
            WRITE (LUPRI,'(//,4(1X,A,2I4,/))')
     &      ' Calculation of integral distribution set:',ISHLA,ISHLB
            WRITE (LUPRI,'(//,4(1X,A,I8,/))')
     &      ' Number of distributions in this set:     ',NUMDIS,
     &      ' Maximum size of scalar integral batch:   ',NSIZG,
     &      ' Number of passes :                       ',NPASS
         END IF
C
         IF (NPASS.GT.1) THEN
C
C           Initialize scalar integral buffer file and arrays
C           Use the space reserved for GMAT now as buffer storage
C
            LGFIL = LUTRA2
            NGBFSZ = (IRAT*NSIZG)/((1+IRAT)*NPASS)
C
C           Allocate the buffer arrays in WORK and set KGMAT to the
C           start of this allocation section. We now only need to
C           send down GMAT into HERMIT to find this section.
C
            CALL MEMGET('INTE',KALGREC,NPASS,WORK,KFREE,LFREE)
            CALL MEMGET('INTE',KALGBUF,NPASS,WORK,KFREE,LFREE)
            CALL MEMGET('INTE',KAIGBUF,NPASS*NGBFSZ,WORK,KFREE,LFREE)
            CALL MEMGET('REAL',KARGBUF,NPASS*NGBFSZ,WORK,KFREE,LFREE)
C
C           As we refer to the places inside the section we need
C           to subtract KGMAT.
C
            KGMAT  = KALGREC
            KLGREC = KALGREC - KGMAT + 1
            KLGBUF = KALGBUF - KGMAT + 1
            KIGBUF = KAIGBUF - KGMAT + 1
            KRGBUF = KARGBUF - KGMAT + 1
         ELSE
C
C           Write directly into the array GMAT
C
            CALL MEMGET('REAL',KGMAT,NSIZG,WORK,KFREE,LFREE)
            CALL DZERO(WORK(KGMAT),NSIZG)
            KLGBUF = 1
            KALGREC = KFREE
         ENDIF
C
C        Get distributions
C
         NODV = NASHT.EQ.0
         NOPV = NASHT.LT.2
         CALL CALDIS(I2TYP,WORK(KGMAT),INDX,WORK(KDXAB),
     &               NODV,NOPV,GABRAO,DRIJ,DINTSKP,SCRTRA,
     &               WORK(KFREE),LFREE,IPRINT)
C
C        Do the transformation of the first index pair and continue
C        by contracting these integrals with the T-amplitudes to obtain
C        the Lagrangian contributions.
C        half-transformed integrals to file.
C
C        De-allocate buffers and allocate GMAT if we had multiple passes.
C
         IF (NPASS.GT.1) THEN
            CALL MEMREL('TRDRV5.1',WORK,1,KALGBUF,KFREE,LFREE)
            CALL MEMGET('REAL',KGMAT,NSIZG,WORK,KFREE,LFREE)
            CALL DZERO(WORK(KGMAT),NSIZG)
         ENDIF
C
         CALL MS3RLAG(WORK,KFREE,LFREE,IPRINT,.TRUE.,.TRUE.,IOFFB,
     &                WORK(KALGREC),ICS12,ICF12,IC,
     &                TRIAN(1),NSTR(1,0,1),NSTR(1,0,2),
     &                WORK(KIJPASS),WORK(KQ(1,1)),WORK(KQ(1,2)),
     &                WORK(KGMAT),NSIZG,
     &                MHTM,IHTM,INDX,WORK(KDXAB),IRECC,WORK(KJBOFF),
     &                IBOFF,NBUF,NIJBUF,NBFSZ,WORK(KRBUF),
     &                WORK(KLBUF1))
C
         CALL MEMREL('TRDRV5.2',WORK,1,KFRSAV3,KFREE,LFREE)
C
C        Delete scalar integral buffer file
C
         IF (NPASS.GT.1) THEN
            CALL DELGBUF(LGFIL)
         ENDIF
C
         DO IREPB = 0,NBSYM-1
            IOFFB(IREPB) = IOFFB(IREPB) + NINSH(ISHLB,IREPB,INDX,IPRINT)
         END DO
      ENDDO
C
C     Release all memory and exit
C
 999  CONTINUE
      CALL MEMREL('TRDRV5.5',WORK,1,KFRSAV,KFREE,LFREE)
      CALL QEXIT('TRDRV5')
C
      RETURN
      END
C&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&
C/* Deck MS3RLAG*/ 
      SUBROUTINE MS3RLAG(WORK,KFREE,LFREE,IPRINT,SUB3,SUB4,IOFF4,LGREC,
     &                   ICS,ICF,IC,
     &                   NSTR1,NSTR2,
     &                   IJPASS,Q1,Q2,Q3,
     &                   GMAT,NSIZG,MHTM,IHTM,INDX,INDXAB)
C&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&&
C     
C     Written by Joost van Stralen & Luuk Visscher April 2003.
C
C     BASD ON : MS4IN1D
C     
C     PURPOSE : Driver for the three-index transformation.
C               Loop over batches for a given shell combination and
C               contract the 3/4 transformed integrals with the
C               T-amplitudes to give a contribution to the Lagrangian.
C     
C     Input :
C
C     - IPRINT       Print flag
C     - NPASS        Number of passes through the scalar integrals
C     - ICS          First class of integrals 1 : (LL|XX), 2 : (SS|XX)
C     - ICL          Last class of integrals
C     - IC           Component of the right hand : (XX|LL) or (XX|SS)
C     - NSTR1        Number of active spinors for index 1
C     - NSTR2        Number of active spinors for index 2
C     - IJPASS       Number of blocks for each boson symmetry
C     - Q1           Coefficients for index 1
C     - Q2           Coefficients for index 2
C     - Q3           Coefficients for index 3 (active AOs only)
C     - GMAT         Symmetry packed scalar integrals
C     - NSIZG        Size of GMAT array
C     - MTHM         Number of scalar integral pairs that contribute
C                    to a given fermion ircop (multiplied with NZ)
C     - ITHM         Start address of a boson representation on the
C                    file of half-transformed integrals.
C     - INDX         For each boson function the boson irrep and the
C                    position in the shell
C     - INDXAB       Information for a pair of boson function belonging
C                    to the current shell pair, 
C           
C     Output :
C           
C     -              Updated Lagrangian
C
#include "implicit.h"
#include "priunit.h"
      PARAMETER(D1 = 1.0D0)
C
      INTEGER   NSTR1(2),NSTR2(2)
      DIMENSION WORK(*)
      DIMENSION Q1(*),Q2(*),GMAT(NSIZG)
      DIMENSION IJPASS(0:7,NPASS),INDX(3,*),IOFF4(0:7)
      LOGICAL   SUB3,SUB4
C
C     For the buffered input
C
      DIMENSION LGREC(NPASS)
C
      DIMENSION IHM(0:7)
C
#include "dgroup.h"
#include "dcbtra.h"
#include "dcbtr3.h"
#include "dcbibt.h"
C
      CALL QENTER('MS4IN1D')
      KFRSAV = KFREE
C
      DO IPASS = 1, NPASS
C
C        Get the scalar integrals that are processed in this pass
C        The integral are already in GMAT when NPASS = 1
C
         IF (NPASS.GT.1) THEN
             CALL DZERO(GMAT,NSIZG)
             IREC = LGREC(IPASS)
             CALL MEMGET('REAL',KRBUF,NGBFSZ,WORK,KFREE,LFREE)
             CALL MEMGET('INTE',KLBUF,NGBFSZ,WORK,KFREE,LFREE)
             CALL READGBF(LGFIL,IREC,WORK(KRBUF),WORK(KLBUF),NGBFSZ,
     &                    GMAT)
             CALL MEMREL('MS4IN1D',WORK,KFRSAV,KRBUF,KFREE,LFREE)
         ENDIF
C
C        Calculate the size of the H-matrix for this pass
C
         NSIZH = 0
         DO IREPAB = 0, NBSYM-1
            IHM(IREPAB) = NSIZH
            IREPIJ = JBTOF(IREPAB,1)
            NSIZH = NSIZH + IJPASS(IREPAB,IPASS)*NFPCK12(IREPIJ)
         ENDDO
C
         CALL MEMGET('REAL',KHMAT,NSIZH*NZ,WORK,KFREE,LFREE)
         CALL DZERO(WORK(KHMAT),NSIZH*NZ)
C
C        Do first step of 4-index transformation :
C        Transform first pair of indices
C
         CALL MS4IN1 (WORK,KFREE,LFREE,IPRINT,ICS,ICF,
     &                TRIAN,NSTR1,NSTR2,NDMOQR,
     &                ICMOQR,IJPASS(0,IPASS),Q1,Q2,
     &                GMAT,WORK(KHMAT))
C
C        Contract with amplitudes and update Lagrangian
C
C        To be written....
C
         CALL MEMREL('MS4IN1D',WORK,KFRSAV,KHMAT,KFREE,LFREE)
C
      ENDDO
C
      CALL QEXIT('MS4IN1D')
      RETURN
      END

