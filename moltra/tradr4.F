C/* Deck Tr4par */
      SUBROUTINE TR4PAR(WORK,KFREE,LFREE,IPRINT,KQ,KE,KIBE,
     &             KINDX,KGAB,KDRIJ,INTFLG,NSTR,ANTIS,
     &             LMP2,EMP2,DINTSKP)
C***********************************************************************
C
C     Slave driver for scheme 4.
C
C     Written by T.Saue Sep 17 1998
C
C***********************************************************************
#include <implicit.h>
#include <priunit.h>
C
#include <mxorb.h>
#if defined (VAR_MPI)
#include <infmpi.h>
      INCLUDE 'mpif.h'
      DIMENSION ISTAT(MPI_STATUS_SIZE)
#else
#include <fpvm3h.h>
#endif
#include <infpar.h>
#include <dcbgen.h>
#include <dcborb.h>
#include <dcbtra.h>
#include <dcbtr3.h>
#include <dcbbas.h>
#include <dgroup.h>
      LOGICAL ANTIS,LMP2,TRIAN(2)
      DIMENSION KQ(2,4),KE(2,4),KIBE(2,4),NSTR(2,0:2,4),IQMO(4,0:7)
      DIMENSION DINTSKP(*),WORK(*)
C
C     Define the packing of the 2-index transformed integrals
C
      KFRSAV = KFREE
      TRIAN(1) = ISAME(2).EQ.ISAME(1)
      TRIAN(2) = .FALSE.
      CALL PCK2IN(NSTR,TRIAN,IPRINT)
C
C     Initialize output file for final integrals
C
      CALL MDSCRI(WORK,KFREE,LFREE,MYTID)
C
C     Wait for tasks until we receive the end message
C
  100 CONTINUE
#if defined (VAR_MPI)
         CALL MPI_SEND(MYTID,1,MPI_INTEGER,MPARID,20,
     &                 MPI_COMM_WORLD,IERR)
         CALL MPI_RECV(ISHLA,1,MPI_INTEGER,MPARID,30,
     &                 MPI_COMM_WORLD,ISTAT,IERR)
         IF (ISHLA.EQ.-1) GOTO 200
         CALL MPI_RECV(IC,1,MPI_INTEGER,MPARID,35,
     &                 MPI_COMM_WORLD,ISTAT,IERR)
#endif
         CALL TRDRV4(WORK,KFREE,LFREE,IPRINT,INTFLG,
     &               NSTR(1,0,1),ANTIS,LMP2,WORK(KINDX),TRIAN,
     &               KQ,KE,KIBE,IC,IQMO,
     &               WORK(KDRIJ),WORK(KGAB),DINTSKP)
         GOTO 100
  200 CONTINUE
C
C     Send results
C
      CALL TRARES(WORK,KFREE,LFREE,DINTSKP,LMP2,DUM,DUM)
C
C     Complete the integrals to the desired classes
C
      CALL MEMGET('INTE',KDXKR12,NFPCK12T*2,WORK,KFREE,LFREE)
      CALL MKINDXKR (NSTR,TRIAN(1),WORK(KDXKR12))
      CALL MEMGET('INTE',KDXB12,NFPCK12T,WORK,KFREE,LFREE)
      CALL MKINDXB (NSTR,WORK(KIBE(1,1)),WORK(KIBE(2,1)),
     &              WORK(KIBE(1,2)),WORK(KIBE(2,2)),
     &              TRIAN(1),WORK(KDXB12))
      CALL MEMGET('INTE',KDXB34,NFPCK34T,WORK,KFREE,LFREE)
      CALL MKINDXB (NSTR,WORK(KIBE(1,3)),WORK(KIBE(2,3)),
     &              WORK(KIBE(1,4)),WORK(KIBE(2,4)),
     &              TRIAN(2),WORK(KDXB34))
C
      NIJOFF = 0
      DO IREPIJ = 1, NFSYM
         NIJ = NFPCK12(IREPIJ)
         CALL DRV4SYM(WORK,KFREE,LFREE,IPRINT,NSTR(1,0,3),NSTR(1,0,4),
     &                IREPIJ,NIJ,IQMO,WORK(KDXKR12),NIJOFF,
     &                WORK(KDXB12),WORK(KDXB34))
         NIJOFF = NIJOFF + NIJ
      ENDDO
C
C     Delete direct access file
C
      CALL MDSCRF
C
      CALL MEMREL('TR4PAR',WORK,KFRSAV,KFRSAV,KFREE,LFREE)
      RETURN
C
      END
