MODULE GRID_FILE
  IMPLICIT NONE
  PRIVATE
  public read_grid  

CONTAINS 
  
  SUBROUTINE READ_GRID(file,points,vc)
#include "priunit.h"
    REAL(kind=8),POINTER :: points(:,:)
    REAL(kind=8),pointer,optional :: vc(:)
    INTEGER                 :: file
    INTEGER                 :: i,npoints
    

    REWIND(file)
    READ(file,*) npoints
    
    ALLOCATE(points(4,1:npoints))
    
    if (present(vc)) then
       ALLOCATE(vc(1:npoints))
       DO i=1,npoints
          READ(file,*) points(:,i),vc(i)
       END DO
    else
       DO i=1,npoints
          READ(file,*) points(:,i)
       END DO
    end if
  END SUBROUTINE READ_GRID
  
  
END MODULE GRID_FILE





