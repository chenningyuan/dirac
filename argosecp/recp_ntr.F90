MODULE RECP_NTR
  REAL(8), ALLOCATABLE :: ctranarg(:, :, :, :)

  INTEGER, ALLOCATABLE :: RECP_CENT(:)
  INTEGER, ALLOCATABLE :: RECP_CORE(:)
  INTEGER, ALLOCATABLE :: AREP_ANG(:)
  INTEGER, ALLOCATABLE :: AREP_BLK(:,:)
  INTEGER, ALLOCATABLE :: AREP_R(:,:,:)
  REAL(8), ALLOCATABLE :: AREP_E(:,:,:)
  REAL(8), ALLOCATABLE :: AREP_C(:,:,:)
  INTEGER, ALLOCATABLE :: SOREP_ANG(:)
  INTEGER, ALLOCATABLE :: SOREP_BLK(:,:)
  INTEGER, ALLOCATABLE :: SOREP_R(:,:,:)
  REAL(8), ALLOCATABLE :: SOREP_E(:,:,:)
  REAL(8), ALLOCATABLE :: SOREP_C(:,:,:)
CONTAINS


SUBROUTINE RECP_NTRA_READCP(MXCENT)
  IMPLICIT NONE
#include "recpval.h"
  INTEGER :: MXCENT

  ALLOCATE(RECP_CENT(MXCENT))
  ALLOCATE(RECP_CORE(MXCENT))

  ALLOCATE(AREP_ANG(MXCENT))
  ALLOCATE(AREP_BLK(MXCENT,RECP_MXANG))
  ALLOCATE(AREP_R(MXCENT,RECP_MXANG,RECP_MXBLK))
  ALLOCATE(AREP_E(MXCENT,RECP_MXANG,RECP_MXBLK))
  ALLOCATE(AREP_C(MXCENT,RECP_MXANG,RECP_MXBLK))

  ALLOCATE(SOREP_ANG(MXCENT))
  ALLOCATE(SOREP_BLK(MXCENT,RECP_MXANG))
  ALLOCATE(SOREP_R(MXCENT,RECP_MXANG,RECP_MXBLK))
  ALLOCATE(SOREP_E(MXCENT,RECP_MXANG,RECP_MXBLK))
  ALLOCATE(SOREP_C(MXCENT,RECP_MXANG,RECP_MXBLK))
END SUBROUTINE RECP_NTRA_READCP

SUBROUTINE RECP_NTRD_READCP
  IMPLICIT NONE

  DEALLOCATE(RECP_CENT)
  DEALLOCATE(RECP_CORE)

  DEALLOCATE(AREP_ANG)
  DEALLOCATE(AREP_BLK)
  DEALLOCATE(AREP_R)
  DEALLOCATE(AREP_E)
  DEALLOCATE(AREP_C)

  DEALLOCATE(SOREP_ANG)
  DEALLOCATE(SOREP_BLK)
  DEALLOCATE(SOREP_R)
  DEALLOCATE(SOREP_E)
  DEALLOCATE(SOREP_C)
END SUBROUTINE RECP_NTRD_READCP

END MODULE RECP_NTR
