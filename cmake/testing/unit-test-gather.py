#!/usr/bin/env python

import os
import glob

cmake_path = os.path.realpath(__file__)[:-19]
f = open(cmake_path + 'autogenerated/Tests.cmake', 'w')

src_path = os.path.realpath( cmake_path + '../../' )
for root, dirs, names in os.walk(src_path):
  if not '.git' in root:
    for d in glob.glob(root + '/*_test'):
      for subd in glob.glob(d + '/*'):
        if os.path.isdir(subd):
          if os.path.isfile(subd + '/test.F90'):
            directory    = d.split('/')[-1]
            path         = d[0:len(d)-len(directory)-1]
            subdirectory = subd.split('/')[-1]
            f.write('add_unit_test(%s %s %s)\n' % (path, directory, subdirectory))

f.close()
