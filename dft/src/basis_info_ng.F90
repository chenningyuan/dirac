!     module for the export/import of basis set information

!     - file is formatted
!     - file is read in free format
!     - sections have labels, the order of section matters:
!           *** geometry
!           *** symmetry_general
!           *** basis_large
!           *** symmetry_large
!           *** basis_small
!           *** symmetry_small
!           *** dirac_specific
!           *** foo_specific
!     - but sections (and labels) can be omitted if irrelevant (e.g. C1)
!     - only 2 sections are mandatory:
!           *** geometry
!           *** basis_large
!     - normalization is absorbed in contraction coefficients
!       (we can discuss this point)
!     - ireps go from 0 to nr_ireps-1

!radovan: notes to myself
!       8. dirac specific information
!          label: "dirac_specific"
!             refine later ...
!             pq_to_uq(4, 0:7)
!             uq_to_pq(4, 0:7)
!             iq(0:3)
!       has to be generated by this module:
!             nr_ao_cartesian (maybe separate in l and s)
!             nr_ao_spherical (maybe separate in l and s)
!             shell_extent(:)
!             cartesian_deg(:)
!             cartesian_off(:)
!             spherical_deg(:)
!             spherical_off(:)
!             nr_so_ao
!             i_so_ao(:, :)
!             f_so_ao(:)
!             cartesian_to_spherical(:)
!             spherical_address(:)

module basis_info_ng

   implicit none

   public basis_info_write_ng
   public basis_info_read_ng

   integer, public :: nr_ireps
   integer, public :: irep_of_axes(3)
   integer, public :: irep_of_rotations(3)
   integer, public :: nr_sym_independent_centers
   integer, public :: nr_sym_dependent_centers

   real(8), public, allocatable :: sym_dependent_center_charge(:)
   real(8), public, allocatable :: sym_dependent_center_xyz(:, :)
   real(8), public, allocatable :: sym_independent_center_charge(:)
   real(8), public, allocatable :: sym_independent_center_xyz(:, :)

   private

   integer              :: nr_shells(0:2)
   integer              :: sym_axes(3, 2)
   integer, parameter   :: nr_types = 2
   integer              :: max_nr_primitives(0:2)
   integer              :: first_shell(0:2)
   integer              :: last_shell(0:2)
   logical              :: is_spherical(0:2)
   integer, allocatable :: shell_type(:)
   integer, allocatable :: shell_center(:)
   integer, allocatable :: shell_stabilizing_irep(:)
   integer, allocatable :: l_quantum_nr(:)
   integer, allocatable :: nr_primitives(:)
   real(8), allocatable :: primitive_exp(:, :)
   real(8), allocatable :: contraction_coef(:, :)

   character(*), parameter :: file_name = 'basis_info_ng'
   integer,      parameter :: file_unit = 137
   logical                 :: file_exists

   character(*), parameter :: type_label(0:2) = (/'total', 'large', 'small'/)

contains

   subroutine basis_info_clear()

!     nr_ireps                   = 1
!     irep_of_axes               = 1
!     irep_of_rotations          = 1
      nr_sym_independent_centers = 0
      nr_sym_dependent_centers   = 0

      if (allocated(sym_dependent_center_charge))   deallocate(sym_dependent_center_charge)
      if (allocated(sym_dependent_center_xyz))      deallocate(sym_dependent_center_xyz)
      if (allocated(sym_independent_center_charge)) deallocate(sym_independent_center_charge)
      if (allocated(sym_independent_center_xyz))    deallocate(sym_independent_center_xyz)

      if (allocated(shell_type))             deallocate(shell_type)
      if (allocated(shell_center))           deallocate(shell_center)
      if (allocated(shell_stabilizing_irep)) deallocate(shell_stabilizing_irep)
      if (allocated(l_quantum_nr))           deallocate(l_quantum_nr)
      if (allocated(nr_primitives))          deallocate(nr_primitives)
      if (allocated(primitive_exp))          deallocate(primitive_exp)
      if (allocated(contraction_coef))       deallocate(contraction_coef)

   end subroutine

   subroutine basis_info_write_ng()

!     --------------------------------------------------------------------------
      integer :: i, j, i_c, i_s, ic
      integer :: ishell, icount, isym, iprim, irep, icent
!     --------------------------------------------------------------------------

#include "mxcent.h"
#include "maxorb.h"
#include "maxaqn.h"
#include "shells.h"
#include "symmet.h"
#include "aovec.h"
#include "primit.h"
#include "sphtrm.h"
#include "dcbbas.h"
#include "pincom.h"
#include "dgroup.h"
#include "dcbham.h"
#include "nuclei.h"

      call basis_info_clear()

!     always regenerate this file
      inquire(file = file_name, exist = file_exists)
      if (file_exists) then
         open(file_unit,            &
              file   = file_name,   &
              status = 'unknown',   &
              form   = 'formatted', &
              access = 'sequential')
         close(file_unit, status = 'delete')
      end if

      open(file_unit,            &
           file   = file_name,   &
           status = 'new',       &
           form   = 'formatted', &
           access = 'sequential')
      rewind(file_unit)

      nr_ireps = nbsym
      sym_axes = isymax

      nr_shells(1) = nlrgsh
      nr_shells(2) = kmax - nr_shells(1)
      nr_shells(0) = nr_shells(1) + nr_shells(2)

      first_shell(1) = 1
      last_shell(1)  = nr_shells(1)
      first_shell(2) = nr_shells(1)  + 1
      last_shell(2)  = last_shell(1) + nr_shells(2)

      allocate(l_quantum_nr(nr_shells(0)))
      allocate(shell_center(nr_shells(0)))
      allocate(shell_stabilizing_irep(nr_shells(0)))
      do ishell = 1, nr_shells(0)
         l_quantum_nr(ishell)           = nhkt(ishell)
         shell_center(ishell)           = ncent(ishell)
         shell_stabilizing_irep(ishell) = istbao(ishell)
      end do

      allocate(shell_type(nr_shells(0)))
      do ishell = 1, nr_shells(0)
         do ic = 1, nr_types
            if (ishell >= first_shell(ic) .and. ishell <= last_shell(ic)) then
               shell_type(ishell) = ic
            end if
         end do
      end do

      max_nr_primitives = 0
      do ishell = 1, nr_shells(0)
         i = jstrt(ishell) + 1
         j = jstrt(ishell) + nuco(ishell)
         icount = 0
         do iprim = i, j
            if (dabs(priccf(iprim, numcf(ishell))) > tiny(0.0d0)) then
               icount = icount + 1
               if (icount > max_nr_primitives(shell_type(ishell))) then
                  max_nr_primitives(shell_type(ishell)) = icount
               end if
            end if
         end do
      end do
      max_nr_primitives(0) = maxval(max_nr_primitives)

      allocate(nr_primitives(nr_shells(0)))
      allocate(primitive_exp(nr_shells(0), max_nr_primitives(0)))
      allocate(contraction_coef(nr_shells(0), max_nr_primitives(0)))

      do ishell = 1, nr_shells(0)
         i = jstrt(ishell) + 1
         j = jstrt(ishell) + nuco(ishell)
         icount = 0
         do iprim = i, j
            if (dabs(priccf(iprim, numcf(ishell))) > tiny(0.0d0)) then
               icount = icount + 1
               nr_primitives(ishell)            = icount
               contraction_coef(ishell, icount) = priccf(iprim, numcf(ishell))
               primitive_exp(ishell, icount)    = priexp(iprim)
            end if
         end do
      end do

      write(file_unit, '(a)') '*** geometry'

      write(file_unit, '(4x, a)') 'nr_sym_independent_centers'
      write(file_unit, '(4x, i6)') nucind

      write(file_unit, '(4x, a)') 'charges_and_coordinates_independent'
      do icent = 1, nucind
         write(file_unit, '(4f26.16)') charge(icent),  &
                                       cord(1, icent), &
                                       cord(2, icent), &
                                       cord(3, icent)
      end do

      write(file_unit, '(4x, a)') 'nr_sym_dependent_centers'
      write(file_unit, '(4x, i6)') nucdep

      write(file_unit, '(4x, a)') 'charges_and_coordinates_dependent'
      do icent = 1, nucind
         if (mult(istbnu(icent)) == 1) then
               write(file_unit, '(4f26.16)') charge(icent),  &
                                             cord(1, icent), &
                                             cord(2, icent), &
                                             cord(3, icent)
         else
            do irep = 0, nr_ireps - 1
               if (iand(irep, istbnu(icent)) == 0) then
                  write(file_unit, '(4f26.16)') charge(icent),                               &
                                                cord(1, icent)*pt(iand(isymax(1, 1), irep)), &
                                                cord(2, icent)*pt(iand(isymax(2, 1), irep)), &
                                                cord(3, icent)*pt(iand(isymax(3, 1), irep))
               end if
            end do
         end if
      end do

      write(file_unit, '(a)') '*** symmetry_general'

      write(file_unit, '(4x, a)') 'nr_ireps'
      write(file_unit, '(4x, i6)') nr_ireps

      write(file_unit, '(4x, a)') 'irep_of_axes'
      write(file_unit, '(4x, i6)') sym_axes(1, 1)
      write(file_unit, '(4x, i6)') sym_axes(2, 1)
      write(file_unit, '(4x, i6)') sym_axes(3, 1)

      write(file_unit, '(4x, a)') 'irep_of_rotations'
      write(file_unit, '(4x, i6)') sym_axes(1, 2)
      write(file_unit, '(4x, i6)') sym_axes(2, 2)
      write(file_unit, '(4x, i6)') sym_axes(3, 2)

      do ic = 1, nr_types

         is_spherical(ic) = .false.
         do ishell = first_shell(ic), last_shell(ic)
            if (sphr(ishell)) then
               is_spherical(ic) = .true.
            end if
         end do

         write(file_unit, '(a)') '*** basis_'//type_label(ic)

         write(file_unit, '(4x, a)') 'is_spherical'
         write(file_unit, '(4x, l6)') is_spherical(ic)

         write(file_unit, '(4x, a)') 'nr_shells'
         write(file_unit, '(4x, i6)') nr_shells(ic)

         write(file_unit, '(4x, a)') 'l_quantum_nr'
         do ishell = first_shell(ic), last_shell(ic)
            write(file_unit, '(4x, i6)') l_quantum_nr(ishell)
         end do

         write(file_unit, '(4x, a)') 'shell_center'
         do ishell = first_shell(ic), last_shell(ic)
            write(file_unit, '(4x, i6)') shell_center(ishell)
         end do

         write(file_unit, '(4x, a)') 'max_nr_primitives'
         write(file_unit, '(4x, i6)') max_nr_primitives(ic)

         write(file_unit, '(4x, a)') 'nr_primitives'
         do ishell = first_shell(ic), last_shell(ic)
            write(file_unit, '(4x, i6)') nr_primitives(ishell)
         end do

         write(file_unit, '(4x, a)') 'primitive_exp_and_contraction_coef'
         do ishell = first_shell(ic), last_shell(ic)
            do i = 1, nr_primitives(ishell)
               write(file_unit, '(2f26.16)') primitive_exp(ishell, i), contraction_coef(ishell, i)
            end do
         end do

         write(file_unit, '(a)') '*** symmetry_'//type_label(ic)

         write(file_unit, '(4x, a)') 'shell_stabilizing_irep'
         do ishell = first_shell(ic), last_shell(ic)
            write(file_unit, '(4x, i6)') shell_stabilizing_irep(ishell)
         end do

         write(file_unit, '(4x, a)') 'nr_ao_in_irep'
         do irep = 0, nr_ireps - 1
            write(file_unit, '(4x, i6)') nbbas(irep, ic)
         end do

         write(file_unit, '(4x, a)') 'ao_offset_in_irep'
         do irep = 0, nr_ireps - 1
            write(file_unit, '(4x, i6)') ibbas(irep, ic)
         end do

      end do

      close(file_unit, status = 'keep')

      call basis_info_clear()

   end subroutine

   subroutine basis_info_read_ng()

!     --------------------------------------------------------------------------
      character(120) :: line
      integer        :: i
      logical        :: symmetry_info_found
!     --------------------------------------------------------------------------

      symmetry_info_found = .false.

      call basis_info_clear()

      inquire(file = file_name, exist = file_exists)
      if (.not. file_exists) then
         print *, 'basis_info_ng file not found'
         stop
      end if

      open(file_unit,            &
           file   = file_name,   &
           status = 'unknown',   &
           form   = 'formatted', &
           access = 'sequential')
      rewind(file_unit)

      do while (.true.)

         read(file_unit, '(a120)', end=1) line

         if (word_contains(line, '*** geometry')) then
            read(file_unit, *)
            read(file_unit, *) nr_sym_independent_centers
            read(file_unit, *)
            allocate(sym_independent_center_charge(nr_sym_independent_centers))
            allocate(sym_independent_center_xyz(nr_sym_independent_centers, 3))
            do i = 1, nr_sym_independent_centers
               read(file_unit, *) sym_independent_center_charge(i), &
                                  sym_independent_center_xyz(i, 1:3)
            end do
            read(file_unit, *)
            read(file_unit, *) nr_sym_dependent_centers
            read(file_unit, *)
            allocate(sym_dependent_center_charge(nr_sym_dependent_centers))
            allocate(sym_dependent_center_xyz(nr_sym_dependent_centers, 3))
            do i = 1, nr_sym_dependent_centers
               read(file_unit, *) sym_dependent_center_charge(i), &
                                  sym_dependent_center_xyz(i, 1:3)
            end do
         end if

         if (word_contains(line, '*** symmetry_general')) then
            symmetry_info_found = .true.
            read(file_unit, *)
            read(file_unit, *) nr_ireps
            read(file_unit, *)
            read(file_unit, *) irep_of_axes(1:3)
            read(file_unit, *)
            read(file_unit, *) irep_of_rotations(1:3)
         end if

!** basis_large
!   is_spherical
!        F
!   nr_shells
!        3
!   l_quantum_nr
!        1
!        1
!        2
!   shell_center
!        1
!        1
!        1
!   max_nr_primitives
!        4
!   nr_primitives
!        4
!        1
!        1
!   primitive_exp_and_contraction_coef
!      13.0099999999999998        0.0961066109833227
!       1.9620000000000000        0.1630199747910442
!       0.4446000000000000        0.1855450226833620
!       0.1220000000000000        0.0737437919835051
!       0.1220000000000000        0.1471227944285736
!       0.7270000000000000        0.9568813750595657
!** symmetry_large
!   shell_stabilizing_irep
!        3
!        3
!        3
!   nr_ao_in_irep
!        3
!        1
!        1
!        0
!        3
!        1
!        1
!        0
!   ao_offset_in_irep
!        0
!       24
!       25
!        3
!       26
!        3
!        4
!       29

      end do
1     continue

      close(file_unit, status = 'keep')

      if (.not. symmetry_info_found) then
         nr_ireps          = 1
         irep_of_axes      = 1
         irep_of_rotations = 1
      end if

   end subroutine

   function word_contains(word, substring)
   
!     --------------------------------------------------------------------------
      character(*), intent(in) :: word
      character(*), intent(in) :: substring
!     --------------------------------------------------------------------------
      logical                  :: word_contains
!     --------------------------------------------------------------------------
      
      if (index(word, substring) > 0) then
         word_contains = .true.
      else
         word_contains = .false.
      end if
   
   end function

end module
