!   ----------------------------------------------------------------------------

    if (l == 1) then
       gao(1) = g_00_00_00_000
       return
    end if

    if (l == 2) then
       gao(1) = g_00_00_00_000*px
       gao(2) = g_00_00_00_000*py
       gao(3) = g_00_00_00_000*pz
