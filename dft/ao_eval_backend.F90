       gao(4)   = g010_000*py
       gao(5)   = g010_000*pz
       gao(6)   = g001_000*pz
       return
    else
       g200_000 = g100_000*px
       g110_000 = g100_000*py
       g101_000 = g100_000*pz
       g020_000 = g010_000*py
       g011_000 = g010_000*pz
       g002_000 = g001_000*pz
    end if

